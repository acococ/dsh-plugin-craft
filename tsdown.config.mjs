// ============================================================================
// tsdown.config.mjs —— 构建配置
// ----------------------------------------------------------------------------
// 关键点：这是一个「只构建宿主端」的构建。
// 0.3.0 把 Client 端整个砍掉了 —— 本插件不再有侧边栏图标，也不再有 Web UI 标签页。
// 它现在只做一件事：注册一个自定义 agent 预设（见 cordis.patch.yml）。
// 所以最终产物只有一个宿主模块，负责挂出 ctx.craft（那个 CraftStore）
// 和挂在它上面的三个 Chat 工具。
// ============================================================================

// 从 tsdown 引入配置定义函数。
import { defineConfig } from 'tsdown'

// 导出配置对象。tsdown 读这个默认值作为构建参数。
export default defineConfig({
  // --------------------------------------------------------------------------
  // 入口
  // --------------------------------------------------------------------------
  // 单一入口。宿主加载的一切都从 src/index.ts 进。
  // 同级的其它模块（store / types / config）会被打进这一个文件里，
  // 而不是各自产出一个文件 —— 装出来的插件就是一个模块。
  entry: { index: 'src/index.ts' },

  // --------------------------------------------------------------------------
  // 输出格式
  // --------------------------------------------------------------------------
  // 只出 ESM，和 package.json 里的 "type": "module" 对齐。
  // 宿主是按 ES module 加载的，多产一份 CJS 纯属浪费。
  format: ['esm'],

  // --------------------------------------------------------------------------
  // 运行环境
  // --------------------------------------------------------------------------
  // Node 专用：store 直接用了 node:fs/promises、node:path、node:crypto。
  platform: 'node',

  // 编译目标 Node 22，和 package.json 的 engines 范围一致。
  target: 'node22',

  // --------------------------------------------------------------------------
  // 类型声明
  // --------------------------------------------------------------------------
  // 产出 lib/index.d.mts。
  // 重点：里面保留的是 src/*.ts 上的 JSDoc 注释 —— 也就是说，
  // 那些注释是写给**外部使用者**看的，发布出去之后会直接出现在
  // 别人的 IDE 提示里。这就是为什么本项目的注释写得比较啰嗦。
  dts: true,

  // --------------------------------------------------------------------------
  // 清理与产物控制
  // --------------------------------------------------------------------------
  // 每次构建前清空 lib/。
  // 作用：万一以后删掉了某个源文件，不会在发布的 tarball 里留下过期产物。
  clean: true,

  // 不产出 sourcemap：产物本来就小，又是塞在插件包里，多这点体积没有意义。
  sourcemap: false,

  // 输出目录。
  outDir: 'lib',

  // 输出的扩展名改用 .mjs。
  // 原因：无论下游文件的 "type" 字段怎么设，.mjs 都一定是合法的 ESM。
  outExtensions: () => ({ js: '.mjs' }),
})
